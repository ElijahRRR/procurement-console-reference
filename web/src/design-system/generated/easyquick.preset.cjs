/** 输入：token 名 → 输出：Tailwind 颜色函数；透明度按 bundle.css 的写法编码为 color-mix。 */
function v(name) {
  const ref = 'var(--' + name.replace(/\./g, '\\.') + ')'
  return function color(opts) {
    const o = opts || {}
    if (o.opacityVariable && (o.opacityValue === undefined || o.opacityValue === 'var(' + o.opacityVariable + ')')) {
      return 'color-mix(in srgb, ' + ref + ' calc(var(' + o.opacityVariable + ', 1) * 100%), transparent)'
    }
    if (o.opacityValue !== undefined && o.opacityValue !== null) {
      return 'color-mix(in srgb, ' + ref + ' calc(' + o.opacityValue + ' * 100%), transparent)'
    }
    return ref
  }
}

